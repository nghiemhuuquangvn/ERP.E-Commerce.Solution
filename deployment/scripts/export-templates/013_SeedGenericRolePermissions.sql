-- for 13 OTHER services that don't exist in this standalone export. Add your own
-- application's permission codes here, following the same pattern — one INSERT
-- block per (view, manage) pair, granted to whichever roles should hold them.
-- Generated by deployment/scripts/export-identity-service.ps1.
-- ============================================================

USE AuthDB;
GO

SET QUOTED_IDENTIFIER ON;
GO

-- ============================================================
-- Sample permissions: sample:widgets:{view,manage} — replace with your own
-- ============================================================
INSERT INTO Permissions (Id, PermissionCode, PermissionName, Module)
SELECT NEWID(), v.Code, v.Name, v.Module
FROM (VALUES
    ('sample:widgets:view', 'View Widgets', 'Sample'),
    ('sample:widgets:manage', 'Manage Widgets', 'Sample')
) AS v(Code, Name, Module)
WHERE NOT EXISTS (SELECT 1 FROM Permissions p WHERE p.PermissionCode = v.Code);
GO

-- Grant to every tenant's SuperAdmin/Admin role (matched by RoleCode, not a fixed
-- GUID — a Role row is per-tenant) — any tenant created after this migration gets
-- these automatically via AuthService.SignupTenantAsync's default role seed.
INSERT INTO RolePermissions (RoleId, PermissionId)
SELECT r.Id, p.Id
FROM Roles r
CROSS JOIN Permissions p
WHERE r.RoleCode IN ('SuperAdmin', 'Admin')
AND p.PermissionCode IN ('sample:widgets:view', 'sample:widgets:manage')
AND NOT EXISTS (SELECT 1 FROM RolePermissions rp WHERE rp.RoleId = r.Id AND rp.PermissionId = p.Id);
GO
