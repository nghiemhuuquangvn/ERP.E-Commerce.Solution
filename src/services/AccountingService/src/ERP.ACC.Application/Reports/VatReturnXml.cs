using System.Globalization;
using System.Text;
using System.Xml;

namespace ERP.ACC.Application.Reports
{
    /// <summary>
    /// The VAT return 01/GTGT as an XML file in the style of the tax authority's HTKK software (ROADMAP P1-3b): taxpayer and period in the header, one element per indicator.
    /// The element names follow the HTKK convention (ct22, ct23 …) but the structure is a reconstruction and has not been validated against the authority's current schema:
    /// the accountant must check it before filing (see docs/business/Accounting/BA-Accounting.md, section 6.27).
    /// </summary>
    public static class VatReturnXml
    {
        public const string Namespace = "http://kekhaithue.gdt.gov.vn/TKhaiThue";

        public static byte[] Build(FinancialStatementDto vatReturn)
        {
            var from = vatReturn.FromDate ?? DateTime.UtcNow.Date;
            var to = vatReturn.ToDate ?? from;
            var settings = new XmlWriterSettings { Indent = true, Encoding = new UTF8Encoding(false), OmitXmlDeclaration = false };
            using var stream = new MemoryStream();
            using (var w = XmlWriter.Create(stream, settings))
            {
                string D(DateTime d) => d.ToString("dd/MM/yyyy", CultureInfo.InvariantCulture);
                w.WriteStartDocument();
                w.WriteComment(" Draft generated by the ERP: HTKK-style structure, NOT validated against the tax authority's schema. Check it before filing. ");
                w.WriteStartElement("HSoThueDTu", Namespace);
                w.WriteStartElement("HSoKhaiThue");
                w.WriteStartElement("TTinChung");
                w.WriteStartElement("TTinTKhaiThue");
                w.WriteStartElement("TKhaiThue");
                w.WriteElementString("maTKhai", "01");
                w.WriteElementString("tenTKhai", "TO KHAI THUE GIA TRI GIA TANG (Mau so 01/GTGT)");
                w.WriteElementString("loaiTKhai", "C");
                w.WriteElementString("soLan", "0");
                w.WriteStartElement("KyKKhaiThue");
                w.WriteElementString("kieuKy", (to - from).Days > 31 ? "Q" : "M");
                w.WriteElementString("kyKKhai", (to - from).Days > 31 ? $"{(from.Month - 1) / 3 + 1}/{from.Year}" : from.ToString("MM/yyyy", CultureInfo.InvariantCulture));
                w.WriteElementString("kyKKhaiTuNgay", D(from));
                w.WriteElementString("kyKKhaiDenNgay", D(to));
                w.WriteEndElement();
                w.WriteElementString("ngayLapTKhai", D(DateTime.UtcNow.Date));
                w.WriteEndElement(); // TKhaiThue
                w.WriteEndElement(); // TTinTKhaiThue
                w.WriteStartElement("NNT");
                w.WriteElementString("mst", vatReturn.Header?.TaxCode ?? string.Empty);
                w.WriteElementString("tenNNT", vatReturn.Header?.CompanyName ?? string.Empty);
                w.WriteElementString("dchiNNT", vatReturn.Header?.Address ?? string.Empty);
                w.WriteEndElement(); // NNT
                w.WriteEndElement(); // TTinChung

                w.WriteStartElement("CTieuTKhaiChinh");
                w.WriteElementString("donViTinh", vatReturn.Unit);
                foreach (var row in vatReturn.Rows)
                    w.WriteElementString("ct" + row.Code, row.Amount.ToString("0.##", CultureInfo.InvariantCulture));
                w.WriteEndElement(); // CTieuTKhaiChinh
                w.WriteElementString("nguoiKy", vatReturn.Header?.ChiefAccountant ?? string.Empty);
                w.WriteEndElement(); // HSoKhaiThue
                w.WriteEndElement(); // HSoThueDTu
                w.WriteEndDocument();
            }
            return stream.ToArray();
        }
    }
}
