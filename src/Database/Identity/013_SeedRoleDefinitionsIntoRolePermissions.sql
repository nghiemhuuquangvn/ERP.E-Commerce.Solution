-- ============================================================
-- AuthDB Schema - IdentityService (Port 5001)
-- Migration 013: One-time seed of ERP.Shared.Authorization.PermissionConstants /
-- RoleDefinitions into AuthDB's Permissions/RolePermissions tables.
--
-- Context: until now, the ~230 business-domain permission codes (crm:*, sales_order:*,
-- payments:*, etc.) that the OTHER 13 services check via [AuthorizePermission(...)] had
-- ZERO rows in this database - they existed only as a hardcoded static C# dictionary
-- (RoleDefinitions.RolePermissions), unioned into every login's JWT permission claims
-- at runtime by AuthService.IssueTokensAsync. This migration makes AuthDB the real
-- source of truth for that union too - AuthService no longer needs the hardcoded
-- fallback once every existing SuperAdmin/Admin/Manager/Purchaser/Viewer role (across
-- every tenant, matched purely by RoleCode) has these same grants persisted here.
--
-- Idempotent: safe to re-run. Matches roles by RoleCode across ALL tenants, not fixed
-- GUIDs, so it also covers any tenant-created role sharing one of these built-in codes.
-- ============================================================

