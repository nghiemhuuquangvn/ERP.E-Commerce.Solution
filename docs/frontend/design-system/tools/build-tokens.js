// Generates the per-app copies of the UI tokens from tokens/tokens.json and checks them.
//   node docs/frontend/design-system/tools/build-tokens.js           write the copies
//   node docs/frontend/design-system/tools/build-tokens.js --check   fail if a copy drifted, a contrast pair fails or a hex sits in app code
// No dependencies. The copies are committed (owner decision 2026-10-28: copied files + drift test, no shared package yet).
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '../../../..')
const tokens = JSON.parse(fs.readFileSync(path.join(__dirname, '../tokens/tokens.json'), 'utf8'))
const check = process.argv.includes('--check')
const GEN = 'GENERATED by docs/frontend/design-system/tools/build-tokens.js from docs/frontend/design-system/tokens/tokens.json - do not edit; change the source and run the script.'

const APPS = [
  { dir: 'src/frontend/admin', kind: 'web', theme: 'back-office', aliases: { primary: { 50: 'subtle', 100: 'soft', 500: 'action', 600: 'action', 700: 'action-hover' } }, code: ['src'] },
  { dir: 'src/frontend/storefront', kind: 'web', theme: 'customer', aliases: { brand: { 100: 'soft', 500: 'action', 600: 'action-hover' } }, code: ['src'] },
  { dir: 'src/frontend/mobile/customer', kind: 'mobile', theme: 'customer', aliases: { brand: { 100: 'soft', 500: 'action', 600: 'action-hover' } }, code: ['app', 'components'] },
  { dir: 'src/frontend/mobile/staff', kind: 'mobile', theme: 'back-office', aliases: { primary: { 50: 'subtle', 500: 'action', 600: 'action' } }, code: ['app', 'components'] },
]

// ---- helpers -------------------------------------------------------------------------------
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16))
const channels = (hex) => rgb(hex).join(' ')
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const lum = (hex) => {
  const c = rgb(hex).map((v) => v / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
}
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05) }

// The flat list of colour roles: [name, hex] with the theme's brand roles resolved.
const roles = (theme) => {
  const t = tokens.themes[theme]
  const s = tokens.semantic
  return [
    ...Object.entries(tokens.neutral),
    ['success', s.success.solid], ['success-soft', s.success.soft], ['success-soft-text', s.success['soft-text']],
    ['warning', s.warning.solid], ['warning-soft', s.warning.soft], ['warning-soft-text', s.warning['soft-text']],
    ['danger', s.danger.solid], ['danger-hover', s.danger.hover], ['danger-soft', s.danger.soft], ['danger-soft-text', s.danger['soft-text']],
    ['info-soft', s.info.soft], ['info-soft-text', s.info['soft-text']],
    ['muted', s.muted.solid], ['muted-soft', s.muted.soft], ['muted-soft-text', s.muted['soft-text']],
    ['brand-action', t.action], ['brand-action-hover', t['action-hover']], ['brand-soft', t.soft],
    ['brand-soft-text', t['soft-text']], ['brand-subtle', t.subtle], ['brand-accent', t.accent],
  ]
}
const hexOf = (theme, name) => roles(theme).find(([n]) => n === name)[1]

// The Tailwind colour tree. `v(name)` returns the value for a role (web: CSS variable, mobile: hex).
const colorTree = (theme, v, aliases) => {
  const brand = { action: v('brand-action'), 'action-hover': v('brand-action-hover'), soft: v('brand-soft'), 'soft-text': v('brand-soft-text'), subtle: v('brand-subtle'), accent: v('brand-accent') }
  const tree = {
    surface: { DEFAULT: v('surface'), muted: v('surface-muted') },
    page: v('page'),
    line: { DEFAULT: v('line'), strong: v('line-strong') },
    ink: { DEFAULT: v('ink'), secondary: v('ink-secondary'), muted: v('ink-muted') },
    'on-brand': v('on-brand'),
    brand,
    success: { DEFAULT: v('success'), soft: v('success-soft'), 'soft-text': v('success-soft-text') },
    warning: { DEFAULT: v('warning'), soft: v('warning-soft'), 'soft-text': v('warning-soft-text') },
    danger: { DEFAULT: v('danger'), hover: v('danger-hover'), soft: v('danger-soft'), 'soft-text': v('danger-soft-text') },
    info: { DEFAULT: v('brand-action'), soft: v('info-soft'), 'soft-text': v('info-soft-text') },
    muted: { DEFAULT: v('muted'), soft: v('muted-soft'), 'soft-text': v('muted-soft-text') },
  }
  // Deprecated numeric names kept so existing class names keep working until U3 (see adoption-roadmap.md).
  for (const [group, map] of Object.entries(aliases)) {
    const target = group === 'brand' ? brand : (tree[group] = {})
    for (const [step, role] of Object.entries(map)) target[step] = brand[role]
  }
  return tree
}
const js = (o) => JSON.stringify(o, null, 2)

// ---- generators ----------------------------------------------------------------------------
const cssBlock = (theme) => roles(theme).map(([n, h]) => `  --c-${n}: ${channels(h)};`).join('\n')
const brandBlock = (theme) => roles(theme).filter(([n]) => n.startsWith('brand-')).map(([n, h]) => `  --c-${n}: ${channels(h)};`).join('\n')

const tokensCss = (app) => `/* ${GEN} */
:root {
${cssBlock(app.theme)}
}
[data-theme='back-office'] {
${brandBlock('back-office')}
}
[data-theme='customer'] {
${brandBlock('customer')}
}
@media (prefers-reduced-motion: reduce) {
  *, ::before, ::after { animation-duration: 0.01ms !important; animation-iteration-count: 1 !important; transition-duration: 0.01ms !important; scroll-behavior: auto !important; }
}
`

const presetCjs = (app) => {
  const v = (n) => `rgb(var(--c-${n}) / <alpha-value>)`
  return `// ${GEN}
module.exports = {
  theme: {
    extend: {
      colors: ${js(colorTree(app.theme, v, app.aliases)).replace(/\n/g, '\n      ')},
      borderRadius: ${js(tokens.radius.web).replace(/\n/g, '\n      ')},
      zIndex: ${js(tokens.zIndex).replace(/\n/g, '\n      ')},
    },
  },
}
`
}

const webTokensTs = (app) => {
  const own = Object.fromEntries(roles(app.theme).map(([n, h]) => [camel(n), h]))
  return `// ${GEN}
// Hex values for code that cannot use a CSS class (charts, canvas). Everything else uses the Tailwind roles.
export const colors = ${js(own)} as const

export const themes = ${js(Object.fromEntries(Object.keys(tokens.themes).map((t) => [t, Object.fromEntries(Object.entries(tokens.themes[t]).map(([k, h]) => [camel(k), h]))])))} as const

export const icon = ${js(tokens.icon)} as const
`
}

const mobileThemeTs = (app) => {
  const own = Object.fromEntries(roles(app.theme).map(([n, h]) => [camel(n), h]))
  return `// ${GEN}
export const colors = ${js(own)} as const

export const radius = ${js(tokens.radius.mobile)} as const

export const icon = ${js(tokens.icon)} as const
`
}

const mobilePresetJs = (app) => {
  const v = (n) => hexOf(app.theme, n)
  return `// ${GEN}
module.exports = {
  theme: {
    extend: {
      colors: ${js(colorTree(app.theme, v, app.aliases)).replace(/\n/g, '\n      ')},
      borderRadius: ${js(tokens.radius.mobile).replace(/\n/g, '\n      ')},
    },
  },
}
`
}

const filesFor = (app) =>
  app.kind === 'web'
    ? { 'src/styles/tokens.css': tokensCss(app), 'src/styles/tokens.ts': webTokensTs(app), 'tokens.preset.cjs': presetCjs(app) }
    : { 'theme/theme.ts': mobileThemeTs(app), 'tailwind.tokens.js': mobilePresetJs(app) }

// ---- checks --------------------------------------------------------------------------------
const norm = (s) => s.replace(/\r\n/g, '\n')
const problems = []

const contrastRules = (theme) => {
  const h = (n) => hexOf(theme, n)
  const rule = (label, fg, bg, min) => ({ label: `${theme}: ${label}`, r: ratio(fg, bg), min })
  return [
    rule('on-brand on brand-action', h('on-brand'), h('brand-action'), 4.5),
    rule('on-brand on brand-action-hover', h('on-brand'), h('brand-action-hover'), 4.5),
    rule('brand-action link on surface', h('brand-action'), h('surface'), 4.5),
    rule('brand-soft-text on brand-soft', h('brand-soft-text'), h('brand-soft'), 4.5),
    rule('brand-soft-text on brand-subtle', h('brand-soft-text'), h('brand-subtle'), 4.5),
    rule('ink on surface', h('ink'), h('surface'), 7),
    rule('ink on page', h('ink'), h('page'), 7),
    rule('ink-secondary on surface', h('ink-secondary'), h('surface'), 4.5),
    rule('ink-muted (placeholder) on surface', h('ink-muted'), h('surface'), 4.5),
    rule('ink-muted on page', h('ink-muted'), h('page'), 4.5),
    rule('line-strong (control border) on surface', h('line-strong'), h('surface'), 3),
    ...['success', 'warning', 'danger'].map((s) => rule(`on-brand on ${s}`, h('on-brand'), h(s), 4.5)),
    rule('on-brand on danger-hover', h('on-brand'), h('danger-hover'), 4.5),
    ...['success', 'warning', 'danger', 'info', 'muted'].map((s) => rule(`${s}-soft-text on ${s}-soft`, h(`${s}-soft-text`), h(`${s}-soft`), 4.5)),
  ]
}

const walk = (dir, out = []) => {
  if (!fs.existsSync(dir)) return out
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'dist' || e.name === '.expo') continue
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else if (/\.(tsx?|jsx?|vue)$/.test(e.name)) out.push(p)
  }
  return out
}

for (const app of APPS) {
  for (const [rel, content] of Object.entries(filesFor(app))) {
    const full = path.join(root, app.dir, rel)
    if (check) {
      if (!fs.existsSync(full)) problems.push(`${app.dir}/${rel}: missing (run build-tokens.js)`)
      else if (norm(fs.readFileSync(full, 'utf8')) !== content) problems.push(`${app.dir}/${rel}: differs from tokens.json (run build-tokens.js)`)
    } else {
      fs.mkdirSync(path.dirname(full), { recursive: true })
      fs.writeFileSync(full, content)
      console.log('wrote', `${app.dir}/${rel}`)
    }
  }
  if (check) {
    for (const sub of app.code) {
      for (const f of walk(path.join(root, app.dir, sub))) {
        if (/[\\/]styles[\\/]tokens\.ts$/.test(f) || /[\\/]theme[\\/]theme\.ts$/.test(f)) continue
        const hits = fs.readFileSync(f, 'utf8').match(/(?<![&\w])#[0-9a-fA-F]{6}\b/g)
        if (hits) problems.push(`${path.relative(root, f)}: hex colour ${[...new Set(hits)].join(', ')} (use a token)`)
      }
    }
  }
}

if (check) {
  for (const theme of Object.keys(tokens.themes)) {
    for (const c of contrastRules(theme)) if (c.r < c.min) problems.push(`contrast ${c.r.toFixed(2)} < ${c.min}: ${c.label}`)
  }
  if (problems.length) {
    console.error(problems.join('\n'))
    console.error(`\n${problems.length} problem(s)`)
    process.exit(1)
  }
  console.log('tokens ok')
}
